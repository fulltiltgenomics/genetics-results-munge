def evidence_tier(source: str, evidence: str) -> str:
    """the strongest tier among the feature's codes; TED domains are predictions by construction."""
    if source == "ted":
        return "predicted"
    tiers = {_ECO_TIER.get(c.strip(), "unknown") for c in (evidence or "").split(",") if c.strip()}
    for t in EVIDENCE_TIERS:
        if t in tiers:
            return t
    return "unknown"


