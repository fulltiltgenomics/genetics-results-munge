def score_percentiles(values: list[float]) -> list[float]:
    """the mid-rank percentile of each value among `values`: 100 * (below + equal / 2) / n.

    Equal values share one percentile and the value itself counts among its equals, so the
    mid-rank is strictly between 0 and 100; what is returned and written is that rounded to
    SCORE_PERCENTILE_DECIMALS, which reaches 0.0 and 100.0 at the ends of a large enough
    population. `values` are means already rounded to SCORE_MEAN_DECIMALS,
    one per distinct (accession, protein_position) of a predictor, so an accession repeated under
    several genes counts once and a reader can recompute a percentile from the file.
    """
    n = len(values)
    order = sorted(values)
    below, equal, i = {}, {}, 0
    while i < n:
        j = i
        while j < n and order[j] == order[i]:
            j += 1
        below[order[i]], equal[order[i]] = i, j - i
        i = j
    return [round(100 * (below[v] + equal[v] / 2) / n, SCORE_PERCENTILE_DECIMALS) for v in values]


# PAE: one row-major n x n uint8 object per model file, symmetrised by minimum within the file
PAE_SCALE = 8
# reserved; no composed matrix is stored, so the build writes it for no entry of this bundle
PAE_NO_VALUE = 255
PAE_MAX_CODE = 254

# SDK limit on one HTTP response
MAX_RESPONSE_BYTES = 16 * 1024 * 1024


def encode_pae(value: float) -> int:
    # `value < c` <=> `code < 8c` for integer c holds only for one-decimal values: a value at
    # c - 0.05 would encode to 8c - 0.4 -> 8c and cross the cutoff. One decimal also keeps 8 *
    # value off .5, so the rounding tie rule never binds
    tenths = value * 10
    if not math.isfinite(value) or value < 0 or abs(tenths - round(tenths)) > 1e-6:
        raise ValueError(f"PAE {value!r} is not a non-negative multiple of 0.1")
    return min(PAE_MAX_CODE, int(math.floor(value * PAE_SCALE + 0.5)))


def decode_pae(code: int) -> float | None:
    return None if code == PAE_NO_VALUE else code / PAE_SCALE


def pae_rows_per_request(n: int) -> int:
    """the most rows of an n x n PAE object one request may ask for: floor(MAX_RESPONSE_BYTES / n)."""
    if n < 1:
        raise ValueError("n must be positive")
    return MAX_RESPONSE_BYTES // n


def owning_window(windows: list[tuple[int, int]]) -> list[tuple[int, int]]:
    """the protein-position range each window owns, for windows sorted by start.

    `windows` are (protein_start, protein_end) of one accession's model files. Window k owns
    up to floor((end_k + start_{k+1}) / 2) and the last window owns up to the protein's end,
    exactly as the lab's get_distance_matrix_structure places its diagonal blocks.
    """
    starts = [s for s, _ in windows]
    if starts != sorted(starts) or len(set(starts)) != len(starts):
        raise ValueError("windows must be sorted by start with distinct starts")
    n = max(e for _, e in windows)
    owned, lo = [], 1
    for k, (_, end) in enumerate(windows):
        nxt = windows[k + 1][0] if k + 1 < len(windows) else n
        hi = (end + nxt) // 2
        owned.append((lo, hi))
        lo = hi + 1
    return owned


def pair_window(windows: list[tuple[int, int]], a: int, b: int) -> int | None:
    """index of the window whose model gives the pair (a, b) of protein positions, or None.

    A pair inside one window's owned range takes that window. Any other pair takes the
    LAST window, in start order, whose model covers both positions; a pair no single model
    covers has no distance and no PAE. This is the lab's composition: every window is first
    written over its whole range in start order, then the owned diagonal blocks overwrite.
    """
    owned = owning_window(windows)
    for k, (lo, hi) in enumerate(owned):
        if lo <= a <= hi and lo <= b <= hi:
            return k
    for k in range(len(windows) - 1, -1, -1):
        s, e = windows[k]
        if s <= a <= e and s <= b <= e:
            return k
    return None


